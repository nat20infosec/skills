#!/usr/bin/env node
// Regenerates the aws-cspm control index from AWS's public Security Hub CSPM docs.
// Only facts are extracted (ID, title, AWS default severity, Config rule, CIS v5.0.0 mapping,
// FSBP / AI-standard membership). No descriptions or remediation text are copied.
//
// usage: node scripts/gen-securityhub-index.mjs [--offline <dir of cached .md pages>] [--out <file>]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : undefined;
};
const offline = arg("--offline");
const outFile =
  arg("--out") ??
  join(here, "..", "plugins", "aws-cspm", "skills", "aws-cspm", "reference", "security-hub-controls.md");

const BASE = "https://docs.aws.amazon.com/securityhub/latest/userguide/";
const cache = new Map();

async function page(slug) {
  if (cache.has(slug)) return cache.get(slug);
  let text;
  if (offline) {
    const p = join(offline, `${slug}.md`);
    if (!existsSync(p)) throw new Error(`offline cache is missing ${slug}.md`);
    text = readFileSync(p, "utf8");
  } else {
    const res = await fetch(`${BASE}${slug}.md`, { headers: { "user-agent": "nat20infosec-skills index generator" } });
    if (!res.ok) throw new Error(`GET ${slug}.md -> ${res.status}`);
    text = await res.text();
    await new Promise((r) => setTimeout(r, 250));
  }
  cache.set(slug, text);
  return text;
}

const master = await page("securityhub-controls-reference");
const masterIds = new Set([...master.matchAll(/\[([A-Za-z0-9]+\.\d+)\]/g)].map((m) => m[1]));
const servicePages = [...new Set([...master.matchAll(/\]\(([a-z0-9-]+-controls)\.md#/g)].map((m) => m[1]))].sort();

const membership = async (slug) =>
  new Set([...(await page(slug)).matchAll(/\[\[([A-Za-z0-9]+\.\d+)\]/g)].map((m) => m[1]));
const fsbp = await membership("fsbp-standard");
const ai = await membership("standards-ai-security");

const controls = [];
for (const slug of servicePages) {
  const text = await page(slug);
  for (const b of text.split(/\n(?=## \[)/).filter((b) => b.startsWith("## ["))) {
    const h = b.match(/^## \[([^\]]+)\]\s*(.+)$/m);
    if (!h) continue;
    const field = (name) => (b.match(new RegExp(`\\*\\*${name}:\\s*\\*\\*\\s*(.*)`)) ?? [, ""])[1].trim();
    const related = field("Related requirements");
    controls.push({
      id: h[1],
      title: h[2].trim(),
      page: slug,
      severity: field("Severity") || "?",
      configRule: (field("AWS Config rule").match(/\[([^\]]+)\]/) ?? [, ""])[1].replace(/`/g, ""),
      cis5: [...related.matchAll(/CIS AWS Foundations Benchmark v5\.0\.0\/([\d.]+)/g)].map((m) => m[1]),
      retired: /retired this control/i.test(b),
    });
  }
}

const parsed = new Set(controls.filter((c) => !c.retired).map((c) => c.id));
const missing = [...masterIds].filter((id) => !parsed.has(id));
if (missing.length) {
  console.error(`FAIL: ${missing.length} control(s) in AWS's master table were not parsed: ${missing.join(", ")}`);
  process.exit(1);
}

const naturalId = (a, b) => {
  const [as, an] = a.id.split("."), [bs, bn] = b.id.split(".");
  return as.localeCompare(bs, "en", { sensitivity: "base" }) || Number(an) - Number(bn);
};
const active = controls.filter((c) => !c.retired).sort(naturalId);
const retired = controls.filter((c) => c.retired).sort(naturalId);
const bySvc = new Map();
for (const c of active) {
  const svc = c.id.split(".")[0];
  if (!bySvc.has(svc)) bySvc.set(svc, []);
  bySvc.get(svc).push(c);
}

const esc = (s) => s.replace(/\|/g, "\\|");
const lines = [];
lines.push(
  "# Security Hub CSPM control index",
  "",
  `Generated by \`scripts/gen-securityhub-index.mjs\` from AWS's public Security Hub CSPM documentation (${new Date().toISOString().slice(0, 10)}). **${active.length} active controls** across ${bySvc.size} services. Do not hand-edit; regenerate.`,
  "",
  "Everything here is AWS's: the IDs, titles, and default severities are theirs, and each service heading links to AWS's page for the check logic, parameters, and remediation. This index only exists so a control ID can be **verified before it is cited** and so a finding can be matched to the AWS Config rule that produces it.",
  "",
  "**The severity column is AWS's default for the rule, not a triage severity.** Rate the finding by exposure path and blast radius per `SKILL.md`.",
  "",
  "Columns: **Std** = `F` in the AWS Foundational Security Best Practices standard, `A` in the AI Security Best Practices standard. **CIS 5.0** = the CIS AWS Foundations Benchmark v5.0.0 requirement AWS maps the control to (blank if none). Cite CIS IDs only from this column, and say the benchmark version.",
  "",
  "To jump to a service, search for `## S3 ` style headings. To check a control's live status in an account: `aws securityhub get-findings --filters '{\"ComplianceSecurityControlId\":[{\"Value\":\"S3.1\",\"Comparison\":\"EQUALS\"}]}'` (needs Security Hub CSPM enabled).",
  "",
);
for (const [svc, list] of bySvc) {
  const pages = [...new Set(list.map((c) => c.page))];
  lines.push(`## ${svc} — ${pages.map((p) => `[AWS docs](${BASE}${p}.html)`).join(", ")}`, "");
  lines.push("| ID | Title | AWS sev | Config rule | Std | CIS 5.0 |", "|---|---|---|---|---|---|");
  for (const c of list) {
    const std = (fsbp.has(c.id) ? "F" : "") + (ai.has(c.id) ? "A" : "");
    lines.push(
      `| ${c.id} | ${esc(c.title)} | ${c.severity} | ${c.configRule ? `\`${c.configRule}\`` : ""} | ${std} | ${c.cis5.join(", ")} |`,
    );
  }
  lines.push("");
}
lines.push(
  "## Retired controls",
  "",
  `AWS has retired these. Never cite them: ${retired.map((c) => c.id).join(", ") || "none"}.`,
  "",
);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"));
console.log(`wrote ${outFile}: ${active.length} active, ${retired.length} retired, ${bySvc.size} services; all ${masterIds.size} master IDs present`);
